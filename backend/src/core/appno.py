"""
출원번호 정규화 공용 모듈.

KIPRIS 원천에 따라 출원번호가 "40-2021-0126877" / "4020210126877" 처럼
포맷이 섞여 들어온다. 이 번호는 파이프라인 전체의 조인 키(파일명, DB PK,
메타 매칭)이므로, 저장·비교 전에 반드시 이 모듈로 통일한다.

2026-07-07 검증에서 확인된 리스크: extract_kipris_images.py 가
pdf 파일명(stem)과 메타의 출원번호를 그대로 교집합해 — 포맷이 다르면
이미지 0건 추출을 조용히 통과한다. 모든 신규 코드는 이 모듈을 쓸 것.
"""

import re

# 상표가 아닌 별개 권리의 출원번호 접두 — 특허(10) / 실용신안(20) / 디자인권(30).
# 이 셋을 제외한 13자리 번호를 상표 데이터로 취급한다(블랙리스트 방식).
#
# 왜 화이트리스트(40/41)가 아닌가 — 2026-07-09 실측 (2026-07-10 정책 적용, 정현수):
#   출원인 "삼성전자"의 등록 도형상표 500건 표본에서 출원번호 접두와 **등록번호** 접두를 대조:
#     40 → 374건 (등록번호 40)   41 → 69건 (등록번호 41)   45 → 15건 (등록번호 45)
#     50 → 18건 (등록번호 **40**)  51 → 12건 (등록번호 **41**)
#     56 → 10건 (등록번호 **40**)  70 →  2건 (등록번호 **40**)
#   45/50/51/56/70 은 특허가 아니라 등록번호가 40/41/45 인 **정식 상표·서비스표**였다
#   (마드리드 가설도 기각 — internationalMark 플래그를 꺼도 잔존). 40/41 화이트리스트는
#   이 표본의 11.4%(57/500)를 근거 없이 버렸다. 원래 필터의 목적은 "심판 API 응답에 섞이는
#   특허(10…) 배제"(TODO.pdf 실측)였으므로, 명백히 상표가 아닌 권리만 제외하는 블랙리스트가
#   목적을 그대로 달성하면서 검색 풀 누락(=선행상표 미검출 위험)을 없앤다.
#   (상세 근거·표본: docs/MarkLens_백엔드6_데이터확장_수집기준_초안.md §ⓑ,
#    docs/MarkLens_트러블슈팅.md TS-03)
NON_TRADEMARK_PREFIXES: tuple[str, ...] = ("10", "20", "30")

# 한국 상표 출원번호는 숫자 13자리 (예: 4020210126877).
APPLICATION_NO_LENGTH: int = 13


def normalize_application_number(raw: str) -> str:
    """
    출원번호 문자열에서 숫자만 남겨 표준형으로 만든다.

    "40-2021-0126877" → "4020210126877"

    Args:
        raw: 원천 출원번호 문자열 (하이픈/공백 포함 가능).

    Returns:
        숫자만 남긴 출원번호 문자열.

    Raises:
        ValueError: 숫자가 하나도 없는 입력.
    """
    digits = re.sub(r"\D", "", raw or "")
    if not digits:
        raise ValueError(f"출원번호로 해석할 수 없는 값: {raw!r}")
    return digits


def is_trademark_application_number(raw: str) -> bool:
    """
    상표 계열 출원번호(13자리, 특허/실용신안/디자인권 아님)인지 검사한다.

    심판·검색 API 응답에서 특허(10)·실용신안(20)·디자인권(30)을 걸러낼 때 사용.
    40/41 외에 45/50/51/56/70 등도 등록번호가 40/41/45 인 정식 상표로 실측 확인되어
    블랙리스트 방식으로 판정한다(모듈 상단 주석 참조). 길이가 다르면 형식 오류로 False.
    """
    try:
        digits = normalize_application_number(raw)
    except ValueError:
        return False
    return (
        len(digits) == APPLICATION_NO_LENGTH
        and not digits.startswith(NON_TRADEMARK_PREFIXES)
    )
